package mentorlooparrayarraylist;

public class whileloop {
	
	public static void main(String[]args) {
		//Print Numbers from 10 to 1
		//Print Odd Numbers from 1 to 19
		
		int i =10;
		while (i>=1) {
			
			System.out.println(i);
			i--;
			
		}
		
		int j =1;
		
		while(j<=20) {
			
			System.out.println("Odd Num: "+j);
			
			j=j+2;
		}
		
		
		
		
		
		
	}

}
