package mentorlooparrayarraylist;

public class forloop {
	public static void main(String[]args) {
	//1. Print Numbers 1 to 20
		//2. Print Even Numbers from 1 to 50
		 
		int i= 20;
		
		for(i=1;i<=20;i++) {
			System.out.println(i);
		}
		
		
		
		int j=50;
		
		for(j=2;j<=50;j=j+2) {
			
			System.out.println("Even num: "+j);
			
			
		}
		
		
		
		
		
		
		
		
	}
	
	

}
