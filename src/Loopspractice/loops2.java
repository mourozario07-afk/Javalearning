package Loopspractice;

public class loops2 {

    public static void main(String[] args) {
        //print 10-1
        int a = 10;
        for(a = 10; a>=1; a--){
            System.out.println("name"+a);
        }
        // print 1-10
        int x=1;

        for (x=1;x<=10;x++){
            System.out.println("Name:"+x);
        }




    }
}
