package Loopspractice;

public class loops3 {
    public static void main(String[]args){
        /*
        Print even numbers from 1 to 50
         */
        int i=2;
        for(i=2;i<=50;i+=2){
            System.out.println("Even Num:"+i);
        }
       /*
        Print odd numbers from 1 to 50
         */
       int j=1;
       for(j=1;j<=50;j+=1){
           System.out.println("Odd Num:"+j);
       }
    }
}
